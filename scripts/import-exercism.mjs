// Imports Exercism's Python practice exercises into content/katas/ (pinned to one commit so it is reproducible).
//   node scripts/import-exercism.mjs [--ref=<sha-or-branch>]
// Exercism content is MIT licensed (see content/katas/LICENSE-exercism.txt); every exercise keeps its authors list.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'content/katas');
const arg = process.argv.find((a) => a.startsWith('--ref='));
const REPO = 'exercism/python';
const gh = async (p) => { const r = await fetch('https://api.github.com' + p, { headers: { 'user-agent': 'senior-interview-lab' } }); if (!r.ok) throw new Error(p + ' ' + r.status); return r.json(); };
const ref = arg ? arg.slice(6) : (await gh(`/repos/${REPO}/commits/main`)).sha;
const raw = async (p) => { const r = await fetch(`https://raw.githubusercontent.com/${REPO}/${ref}/${p}`); return r.ok ? r.text() : null; };

const config = JSON.parse(await raw('config.json'));
const practice = config.exercises.practice;
console.log(`${practice.length} practice exercises at ${ref.slice(0, 10)}`);
fs.mkdirSync(path.join(out, 'python'), { recursive: true });

/* Excluded: cannot run in a single browser worker. Refactor katas start from working code, so their stub passes by design. */
const EXCLUDE = { 'error-handling': 'needs a helper test module', 'parallel-letter-frequency': 'needs real threads/processes', paasio: 'multi-file exercise' };
const REFACTOR = new Set(['ledger', 'markdown']);
for (const f of fs.readdirSync(path.join(out, 'python'))) fs.unlinkSync(path.join(out, 'python', f));
const index = [], skipped = [];
let next = 0;
async function one(ex) {
  if (EXCLUDE[ex.slug]) return skipped.push([ex.slug, EXCLUDE[ex.slug]]);
  const base = `exercises/practice/${ex.slug}`;
  const meta = JSON.parse((await raw(`${base}/.meta/config.json`)) || 'null');
  if (!meta) return skipped.push([ex.slug, 'no config']);
  const f = meta.files || {};
  if ((f.solution || []).length !== 1 || (f.test || []).length !== 1 || (f.example || []).length !== 1) return skipped.push([ex.slug, 'not a single-file exercise']);
  const [stub, tests, example, intro, instr, append, hints] = await Promise.all([
    raw(`${base}/${f.solution[0]}`), raw(`${base}/${f.test[0]}`), raw(`${base}/${f.example[0]}`),
    raw(`${base}/.docs/introduction.md`), raw(`${base}/.docs/instructions.md`), raw(`${base}/.docs/instructions.append.md`), raw(`${base}/.docs/hints.md`),
  ]);
  if (stub == null || tests == null || example == null || instr == null) return skipped.push([ex.slug, 'missing file']);
  const module = f.solution[0].replace(/\.py$/, '');
  const data = {
    slug: ex.slug, name: ex.name, blurb: meta.blurb || '', difficulty: ex.difficulty, module,
    authors: meta.authors || [], contributors: meta.contributors || [], source: meta.source || '', source_url: meta.source_url || '',
    instructions: [intro, instr, append].filter(Boolean).join('\n\n'), hints: hints || '',
    stub, tests, example, ...(REFACTOR.has(ex.slug) ? { refactor: true } : {}),
  };
  fs.writeFileSync(path.join(out, 'python', ex.slug + '.json'), JSON.stringify(data));
  index.push({ slug: ex.slug, name: ex.name, blurb: data.blurb, difficulty: ex.difficulty, ...(data.refactor ? { refactor: true } : {}) });
}
await Promise.all(Array.from({ length: 8 }, async () => { while (next < practice.length) await one(practice[next++]).catch((e) => skipped.push([practice[next - 1]?.slug, String(e.message || e)])); }));

index.sort((a, b) => a.difficulty - b.difficulty || a.name.localeCompare(b.name));
fs.writeFileSync(path.join(out, 'index.js'),
  `/* Generated by scripts/import-exercism.mjs. Exercism Python practice exercises (MIT), pinned at ${ref}. */\n` +
  `window.KATAS = ${JSON.stringify({ source: REPO, ref, license: 'MIT', skipped, items: index })};\n`);
const lic = await raw('LICENSE');
if (lic) fs.writeFileSync(path.join(out, 'LICENSE-exercism.txt'), `Exercises in this folder come from https://github.com/${REPO} (commit ${ref}).\nEach exercise's .json file lists its authors and contributors.\n\n${lic}`);
console.log(`imported ${index.length}, skipped ${skipped.length}`, skipped.slice(0, 10));
