import { newPage } from './helpers.mjs';

export default async function ({ url, browser, ok, section }) {
  const page = await newPage(browser, { viewport: { width: 390, height: 844 } });
  await page.goto(url + '#/stories');
  await page.locator('#snew').waitFor();
  section('recoverable behavioral story drafts');
  await page.locator('#snew').click();
  await page.locator('#stitle').fill('Recover the incident');
  await page.locator('textarea[data-k="a"]').fill('I isolated the deploy, compared traces and rolled back the failing change.');
  await page.locator('[data-t="incident"]').click();
  await page.reload();
  await page.locator('#sresume').click();
  ok(await page.locator('#stitle').inputValue() === 'Recover the incident', 'new story title survives reload');
  ok((await page.locator('textarea[data-k="a"]').inputValue()).includes('compared traces'), 'STAR writing survives reload');
  ok(await page.locator('[data-t="incident"]').evaluate(el => el.classList.contains('on')), 'competency tags survive reload');
  await page.go(url, '#/resources');
  await page.go(url, '#/stories');
  ok(await page.locator('#stitle').inputValue() === 'Recover the incident', 'draft survives route navigation');
  await page.locator('#scancel').click();
  ok(await page.locator('#sresume').count() === 1, 'return to bank preserves unfinished draft');
  await page.locator('#sresume').click();
  await page.locator('#ssave').click();
  ok(await page.locator('#sresume').count() === 0, 'explicit save clears draft recovery');
  ok((await page.locator('.scard').innerText()).includes('structure'), 'heuristics are labeled as structure rather than readiness');
  await page.locator('[data-e]').click();
  await page.locator('textarea[data-k="r"]').fill('Recovered service in 12 minutes.');
  await page.reload();
  await page.locator('#sresume').click();
  ok((await page.locator('textarea[data-k="r"]').inputValue()).includes('12 minutes'), 'edits to an existing story survive reload');
  await page.locator('#ssave').click();
  section('actionable practice reflection');
  await page.locator('[data-p]').click();
  await page.locator('#pstart').click();
  await page.locator('#ppeek').click();
  await page.locator('#pdone').click();
  const check = page.locator('#prub li').nth(1);
  await check.focus();
  await page.keyboard.press('Space');
  ok(await check.getAttribute('aria-checked') === 'true', 'self-reflection check supports keyboard');
  ok((await page.locator('#pself').innerText()).includes('opened the outline'), 'practice feedback records outline use');
  await page.locator('#pnext').fill('Explain why I rolled back before discussing recovery.');
  await page.locator('#psave').click();
  ok((await page.locator('.scard').innerText()).includes('Explain why I rolled back'), 'next practice action is visible on story card');
  ok((await page.locator('.scard').innerText()).includes('outline used'), 'saved attempt shows delivery evidence');
  await page.reload();
  ok((await page.locator('.scard').innerText()).includes('Explain why I rolled back'), 'reflection survives reload');
  ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'story card fits phone width');
  ok(page.errors.length === 0, 'story flow has no browser errors');
  await page.context().close();
}
